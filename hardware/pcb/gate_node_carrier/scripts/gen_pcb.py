#!/usr/bin/env python3
"""Generate gate_node_carrier.kicad_pcb (KiCad 6) from design.py.

Places every footprint, assigns nets, links each footprint to its schematic
symbol UUID (so Tools > Update PCB from Schematic works), draws the outline,
silkscreen labels and GND pours on both layers. Tracks are routed in KiCad.

Usage:  python3 scripts/gen_pcb.py [--check]
        --check : only report courtyard overlaps / off-board parts, don't write
"""
import itertools
import json
import os
import sys

import pcbnew

import design
from gen_schematic import symbol_uuid

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.join(PROJ, "gate_node_carrier.kicad_pcb")
STD_FP = "/usr/share/kicad/footprints"
LOCAL_LIBS = {"gate_node": os.path.join(PROJ, "gate_node.pretty")}

MM = pcbnew.FromMM

# Extra 3D placeholders (from gen_3d.py) attached to board footprints.
# The Heltec body rides on J1 because J1 pin 1 is its reference point.
PLACEHOLDER_MODELS = {"J1": "Heltec_V3_placeholder.wrl"}


def pt(x, y):
    return pcbnew.wxPointMM(x, y)


def load_fp(fpid):
    lib, name = fpid.split(":")
    path = LOCAL_LIBS.get(lib, os.path.join(STD_FP, lib + ".pretty"))
    fp = pcbnew.FootprintLoad(path, name)
    if fp is None:
        raise RuntimeError(f"footprint not found: {fpid}")
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    return fp


def add_line(board, x1, y1, x2, y2, layer, width):
    s = pcbnew.PCB_SHAPE(board)
    s.SetShape(pcbnew.SHAPE_T_SEGMENT)
    s.SetStart(pt(x1, y1))
    s.SetEnd(pt(x2, y2))
    s.SetLayer(layer)
    s.SetWidth(MM(width))
    board.Add(s)


def add_rect(board, x1, y1, x2, y2, layer, width):
    for a, b in [((x1, y1), (x2, y1)), ((x2, y1), (x2, y2)),
                 ((x2, y2), (x1, y2)), ((x1, y2), (x1, y1))]:
        add_line(board, *a, *b, layer, width)


def add_text(board, text, x, y, size, layer=pcbnew.F_SilkS):
    t = pcbnew.PCB_TEXT(board)
    t.SetText(text)
    t.SetPosition(pt(x, y))
    t.SetLayer(layer)
    t.SetTextSize(pcbnew.wxSizeMM(size, size))
    t.SetTextThickness(MM(max(0.12, size * 0.15)))
    board.Add(t)


def add_gnd_zone(board, net, layer, x1, y1, x2, y2):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    z.SetNet(net)
    z.SetLocalClearance(MM(0.4))
    z.SetMinThickness(MM(0.25))
    z.SetPadConnection(pcbnew.ZONE_CONNECTION_THERMAL)
    z.SetThermalReliefGap(MM(0.4))
    z.SetThermalReliefSpokeWidth(MM(0.5))
    ol = z.Outline()
    ol.NewOutline()
    for x, y in [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]:
        ol.Append(MM(x), MM(y))
    board.Add(z)
    return z


def courtyard_box(fp):
    rects = [g.GetBoundingBox() for g in fp.GraphicalItems() if g.GetLayer() == pcbnew.F_CrtYd]
    if not rects:
        rects = [fp.GetBoundingBox(False, False)]
    return (min(pcbnew.ToMM(r.GetX()) for r in rects),
            min(pcbnew.ToMM(r.GetY()) for r in rects),
            max(pcbnew.ToMM(r.GetRight()) for r in rects),
            max(pcbnew.ToMM(r.GetBottom()) for r in rects))


def build():
    board = pcbnew.NewBoard(OUT)
    tb = board.GetTitleBlock()
    tb.SetTitle("Gate Node Carrier")
    tb.SetRevision("A")
    tb.SetComment(0, "Generated by scripts/gen_pcb.py - placement only, route in KiCad")

    nets = {}
    for _, _, _, netmap, _, _ in design.PARTS.values():
        for n in netmap.values():
            if n and n not in nets:
                ni = pcbnew.NETINFO_ITEM(board, n)
                board.Add(ni)
                nets[n] = ni

    fps = {}
    for ref, (lib_id, value, fpid, netmap, group, desc) in design.PARTS.items():
        fp = load_fp(fpid)
        fp.SetReference(ref)
        fp.SetValue(value.split(" (")[0])
        fp.SetPath(pcbnew.KIID_PATH("/" + symbol_uuid(ref)))
        x, y, rot = design.PLACEMENT[ref]
        fp.SetPosition(pt(x, y))
        fp.SetOrientationDegrees(rot)
        for pad in fp.Pads():
            n = netmap.get(pad.GetNumber())
            if n:
                pad.SetNet(nets[n])
        if ref in PLACEHOLDER_MODELS:
            m = pcbnew.FP_3DMODEL()
            m.m_Filename = "${KIPRJMOD}/gate_node.3dshapes/" + PLACEHOLDER_MODELS[ref]
            m.m_Show = True
            fp.Add3DModel(m)
        board.Add(fp)
        fps[ref] = fp

    x0, y0 = design.ORIGIN
    x1, y1 = x0 + design.BOARD_W, y0 + design.BOARD_H
    add_rect(board, x0, y0, x1, y1, pcbnew.Edge_Cuts, 0.1)

    hx1, hy1, hx2, hy2 = design.HELTEC_OUTLINE
    add_rect(board, hx1, hy1, hx2, hy2, pcbnew.F_SilkS, 0.15)
    for text, x, y, size in design.SILK_TEXT:
        add_text(board, text, x, y, size)

    # Net classes are stored in the .kicad_pro in KiCad 6 -- see write_project()
    inset = 0.5
    for layer in (pcbnew.F_Cu, pcbnew.B_Cu):
        add_gnd_zone(board, nets["GND"], layer, x0 + inset, y0 + inset, x1 - inset, y1 - inset)

    return board, fps


def check(fps):
    x0, y0 = design.ORIGIN
    x1, y1 = x0 + design.BOARD_W, y0 + design.BOARD_H
    boxes = {r: courtyard_box(f) for r, f in fps.items()}
    problems = []
    for r, (a, b, c, d) in boxes.items():
        if a < x0 or b < y0 or c > x1 or d > y1:
            problems.append(f"{r} courtyard off board: ({a:.1f},{b:.1f})-({c:.1f},{d:.1f})")
    heltec = design.HELTEC_OUTLINE
    for (ra, A), (rb, B) in itertools.combinations(boxes.items(), 2):
        if A[0] < B[2] and B[0] < A[2] and A[1] < B[3] and B[1] < A[3]:
            problems.append(f"courtyard overlap: {ra} / {rb}")
    for r, A in boxes.items():
        if r in ("J1", "J2"):
            continue
        if A[0] < heltec[2] and heltec[0] < A[2] and A[1] < heltec[3] and heltec[1] < A[3]:
            problems.append(f"{r} sits under the Heltec module outline")
    return problems, boxes


def write_project():
    """Create/patch gate_node_carrier.kicad_pro with net classes."""
    path = os.path.join(PROJ, "gate_node_carrier.kicad_pro")
    proj = {}
    if os.path.exists(path):
        with open(path) as f:
            proj = json.load(f)
    proj.setdefault("meta", {"filename": "gate_node_carrier.kicad_pro", "version": 1})
    base = {"bus_width": 12.0, "diff_pair_gap": 0.25, "diff_pair_via_gap": 0.25,
            "diff_pair_width": 0.2, "line_style": 0, "microvia_diameter": 0.3,
            "microvia_drill": 0.1, "pcb_color": "rgba(0, 0, 0, 0.000)",
            "schematic_color": "rgba(0, 0, 0, 0.000)", "wire_width": 6.0}
    proj["net_settings"] = {
        "classes": [
            dict(base, name="Default", clearance=0.25, track_width=0.3,
                 via_diameter=0.8, via_drill=0.4),
            dict(base, name="Power", clearance=0.3, track_width=0.8,
                 via_diameter=1.0, via_drill=0.5, nets=sorted(design.POWER_NETS)),
        ],
        "meta": {"version": 2},
        "net_colors": None,
    }
    with open(path, "w") as f:
        json.dump(proj, f, indent=2)
        f.write("\n")
    print("wrote", os.path.relpath(path))


def main():
    board, fps = build()
    problems, _ = check(fps)
    for p in problems:
        print("WARN:", p)
    print(f"{len(fps)} footprints, {len(problems)} placement warnings")
    if "--check" in sys.argv:
        return
    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    pcbnew.SaveBoard(OUT, board)
    print("wrote", os.path.relpath(OUT))
    write_project()


if __name__ == "__main__":
    main()
