#!/usr/bin/env python3
"""Generate simple box placeholder 3D models (VRML for the viewer, STEP for export).

Models are written to ../gate_node.3dshapes/<name>.wrl and .step. KiCad's
STEP exporter swaps a .wrl model for a .step file with the same name.

Coordinates are in the *footprint* frame of the footprint the model is
attached to, in mm, with KiCad's 3D convention: +X right, +Y up (footprint Y
inverted) and +Z out of the carrier board's top surface.
"""
import os

import design

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.abspath(os.path.join(HERE, "..", "gate_node.3dshapes"))

WHITE = (0.92, 0.92, 0.90)
BLACK = (0.05, 0.05, 0.06)
GLASS = (0.10, 0.12, 0.20)
SILVER = (0.75, 0.75, 0.78)
GOLD = (0.85, 0.70, 0.25)
GREEN = (0.10, 0.45, 0.20)
DARK = (0.20, 0.20, 0.22)


def box(x0, y0, z0, x1, y1, z1, color, name):
    return dict(lo=(min(x0, x1), min(y0, y1), min(z0, z1)),
                hi=(max(x0, x1), max(y0, y1), max(z0, z1)), color=color, name=name)


# ------------------------------------------------------------------ Heltec V3
def heltec_boxes():
    """Attached to J1 (Heltec J3 row). J1 pin 1 is the footprint origin and its
    pins run along footprint +Y, which is model -Y. The J2 row is at footprint
    -X 23.04 mm (the footprint is rotated 90 deg on the board)."""
    row = design.HELTEC_ROW_SPACING
    usb = design.HELTEC_PIN1_X - design.HELTEC_USB_FACE_X     # 3.36 mm
    w = 25.52
    cx = -row / 2                       # board centre line (footprint X)
    y_usb, y_end = usb, usb - 50.2      # model Y: USB face .. far end
    socket_h = 8.5                      # 2.54 mm female header body height
    pcb_t = 1.0
    z_pcb = socket_h + pcb_t
    b = [
        box(cx - w / 2, y_usb - 0.66, socket_h, cx + w / 2, y_end, z_pcb, WHITE, "heltec_pcb"),
        # OLED frame and glass: frame starts ~15 mm from the USB face, 33.28 x 18.56
        box(cx - 9.28, y_usb - 15.0, z_pcb, cx + 9.28, y_usb - 48.28, z_pcb + 1.6, BLACK, "oled_frame"),
        box(cx - 7.5, y_usb - 18.0, z_pcb + 1.6, cx + 7.5, y_usb - 45.28, z_pcb + 2.4, GLASS, "oled_glass"),
        # USB-C receptacle, overhanging the Heltec edge by ~0.66 mm
        box(cx - 4.5, y_usb, z_pcb, cx + 4.5, y_usb - 7.4, z_pcb + 3.2, SILVER, "usb_c"),
        # PRG / RST buttons either side of the USB-C
        box(cx - 11.0, y_usb - 4.0, z_pcb, cx - 7.5, y_usb - 7.5, z_pcb + 1.5, DARK, "btn_prg"),
        box(cx + 7.5, y_usb - 4.0, z_pcb, cx + 11.0, y_usb - 7.5, z_pcb + 1.5, DARK, "btn_rst"),
        # U.FL antenna connector near the far end
        box(cx + 5.0, y_end + 6.0, z_pcb, cx + 8.0, y_end + 3.0, z_pcb + 1.3, GOLD, "ufl"),
    ]
    # Male header pins from the Heltec into the sockets (both rows)
    for col in (0.0, -row):
        for i in range(18):
            y = -i * 2.54
            b.append(box(col - 0.32, y - 0.32, 2.5, col + 0.32, y + 0.32, z_pcb + 0.6,
                         GOLD, f"pin_{int(-col)}_{i + 1}"))
    return b


# ------------------------------------------------------------------ Mini360
def mini360_boxes():
    """Attached to the gate_node:Mini360_MP1584 footprint (origin = module centre)."""
    z0, t = 3.0, 1.0      # module seated on ~3 mm of header pin
    b = [
        box(-8.6, -5.6, z0, 8.6, 5.6, z0 + t, GREEN, "mini360_pcb"),
        box(-1.0, -3.5, z0 + t, 4.0, 1.5, z0 + t + 2.0, DARK, "inductor"),
        box(-5.5, -1.5, z0 + t, -2.5, 1.5, z0 + t + 1.0, BLACK, "ic"),
        box(4.8, 1.8, z0 + t, 6.8, 3.8, z0 + t + 1.2, (0.6, 0.45, 0.2), "cap"),
    ]
    for px, py in [(-7.3, 4.3), (-7.3, -4.3), (7.3, -4.3), (7.3, 4.3)]:
        b.append(box(px - 0.32, py - 0.32, -1.5, px + 0.32, py + 0.32, z0 + t + 0.5,
                     GOLD, "pin"))
    return b


# ------------------------------------------------------------------ writers
def corners(bx):
    (x0, y0, z0), (x1, y1, z1) = bx["lo"], bx["hi"]
    return [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
            (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]


# Faces as corner indices, counter-clockwise seen from outside (outward normal)
FACES = [
    ((0, 3, 2, 1), (0, 0, -1)),   # bottom
    ((4, 5, 6, 7), (0, 0, 1)),    # top
    ((0, 1, 5, 4), (0, -1, 0)),   # front (-Y)
    ((1, 2, 6, 5), (1, 0, 0)),    # right (+X)
    ((2, 3, 7, 6), (0, 1, 0)),    # back (+Y)
    ((3, 0, 4, 7), (-1, 0, 0)),   # left (-X)
]


def write_wrl(path, boxes):
    """VRML 2.0. KiCad reads VRML in units of 0.1 inch."""
    s = 1 / 2.54
    out = ["#VRML V2.0 utf8", "# Placeholder generated by scripts/gen_3d.py"]
    for bx in boxes:
        r, g, b = bx["color"]
        pts = ", ".join(f"{x * s:.4f} {y * s:.4f} {z * s:.4f}" for x, y, z in corners(bx))
        idx = ", ".join(" ".join(map(str, f)) + " -1" for f, _ in FACES)
        out.append(
            "Shape {\n"
            f"  appearance Appearance {{ material Material {{ diffuseColor {r} {g} {b} "
            "specularColor 0.2 0.2 0.2 shininess 0.3 } }\n"
            f"  geometry IndexedFaceSet {{ solid TRUE coord Coordinate {{ point [ {pts} ] }} "
            f"coordIndex [ {idx} ] }}\n"
            "}")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


class StepWriter:
    def __init__(self):
        self.lines = []
        self.n = 0

    def add(self, text):
        self.n += 1
        self.lines.append(f"#{self.n}={text};")
        return f"#{self.n}"


def write_step(path, name, boxes):
    """AP214 STEP: one manifold solid B-rep per box, coloured per box."""
    w = StepWriter()
    ctx_app = w.add("APPLICATION_CONTEXT('core data for automotive mechanical design processes')")
    w.add(f"APPLICATION_PROTOCOL_DEFINITION('international standard','automotive_design',2000,{ctx_app})")
    prod_ctx = w.add(f"PRODUCT_CONTEXT('',{ctx_app},'mechanical')")
    prod = w.add(f"PRODUCT('{name}','{name}','',({prod_ctx}))")
    pdf = w.add(f"PRODUCT_DEFINITION_FORMATION('','',{prod})")
    pd_ctx = w.add(f"PRODUCT_DEFINITION_CONTEXT('part definition',{ctx_app},'design')")
    pdef = w.add(f"PRODUCT_DEFINITION('design','',{pdf},{pd_ctx})")
    pds = w.add(f"PRODUCT_DEFINITION_SHAPE('','',{pdef})")
    length = w.add("(LENGTH_UNIT()NAMED_UNIT(*)SI_UNIT(.MILLI.,.METRE.))")
    angle = w.add("(NAMED_UNIT(*)PLANE_ANGLE_UNIT()SI_UNIT($,.RADIAN.))")
    solid_angle = w.add("(NAMED_UNIT(*)SI_UNIT($,.STERADIAN.)SOLID_ANGLE_UNIT())")
    unc = w.add(f"UNCERTAINTY_MEASURE_WITH_UNIT(LENGTH_MEASURE(1.E-07),{length},'distance_accuracy_value','')")
    geo_ctx = w.add(f"(GEOMETRIC_REPRESENTATION_CONTEXT(3)GLOBAL_UNCERTAINTY_ASSIGNED_CONTEXT(({unc}))"
                    f"GLOBAL_UNIT_ASSIGNED_CONTEXT(({length},{angle},{solid_angle}))"
                    "REPRESENTATION_CONTEXT('Context #1','3D Context with UNIT and UNCERTAINTY'))")

    def pnt(p):
        return w.add("CARTESIAN_POINT('',(%.4f,%.4f,%.4f))" % p)

    def dirn(d):
        return w.add("DIRECTION('',(%.1f,%.1f,%.1f))" % d)

    origin = pnt((0, 0, 0))
    world = w.add(f"AXIS2_PLACEMENT_3D('',{origin},{dirn((0, 0, 1))},{dirn((1, 0, 0))})")

    solids, styled = [], []
    for bx in boxes:
        cs = corners(bx)
        verts = [w.add(f"VERTEX_POINT('',{pnt(c)})") for c in cs]
        edges = {}

        def edge(a, b):
            key = (min(a, b), max(a, b))
            if key not in edges:
                i, j = key
                d = tuple(cs[j][k] - cs[i][k] for k in range(3))
                ln = max(abs(v) for v in d)
                unit = tuple(v / ln for v in d)
                line = w.add(f"LINE('',{pnt(cs[i])},VECTOR('',{dirn(unit)},{ln:.4f}))")
                edges[key] = w.add(f"EDGE_CURVE('',{verts[i]},{verts[j]},{line},.T.)")
            return edges[key], (a, b) == key

        faces = []
        for idx, normal in FACES:
            oes = []
            for k in range(4):
                e, same = edge(idx[k], idx[(k + 1) % 4])
                oes.append(w.add(f"ORIENTED_EDGE('',*,*,{e},{'.T.' if same else '.F.'})"))
            loop = w.add(f"EDGE_LOOP('',({','.join(oes)}))")
            bound = w.add(f"FACE_OUTER_BOUND('',{loop},.T.)")
            c0, c1 = cs[idx[0]], cs[idx[1]]
            ref = tuple(c1[k] - c0[k] for k in range(3))
            ln = max(abs(v) for v in ref)
            ref = tuple(v / ln for v in ref)
            plane = w.add(f"PLANE('',AXIS2_PLACEMENT_3D('',{pnt(c0)},{dirn(normal)},{dirn(ref)}))")
            faces.append(w.add(f"ADVANCED_FACE('',({bound}),{plane},.T.)"))
        shell = w.add(f"CLOSED_SHELL('',({','.join(faces)}))")
        solid = w.add(f"MANIFOLD_SOLID_BREP('{bx['name']}',{shell})")
        solids.append(solid)

        r, g, b = bx["color"]
        col = w.add(f"COLOUR_RGB('',{r:.3f},{g:.3f},{b:.3f})")
        fill = w.add(f"FILL_AREA_STYLE('',(FILL_AREA_STYLE_COLOUR('',{col})))")
        ssa = w.add(f"SURFACE_SIDE_STYLE('',(SURFACE_STYLE_FILL_AREA({fill})))")
        psa = w.add(f"PRESENTATION_STYLE_ASSIGNMENT((SURFACE_STYLE_USAGE(.BOTH.,{ssa})))")
        styled.append(w.add(f"STYLED_ITEM('color',({psa}),{solid})"))

    rep = w.add(f"ADVANCED_BREP_SHAPE_REPRESENTATION('{name}',({world},{','.join(solids)}),{geo_ctx})")
    w.add(f"SHAPE_DEFINITION_REPRESENTATION({pds},{rep})")
    w.add(f"MECHANICAL_DESIGN_GEOMETRIC_PRESENTATION_REPRESENTATION('',({','.join(styled)}),{geo_ctx})")

    header = ("ISO-10303-21;\nHEADER;\n"
              "FILE_DESCRIPTION(('placeholder generated by gen_3d.py'),'2;1');\n"
              f"FILE_NAME('{name}.step','',(''),(''),'gen_3d.py','','');\n"
              "FILE_SCHEMA(('AUTOMOTIVE_DESIGN { 1 0 10303 214 1 1 1 1 }'));\nENDSEC;\nDATA;\n")
    with open(path, "w") as f:
        f.write(header + "\n".join(w.lines) + "\nENDSEC;\nEND-ISO-10303-21;\n")


MODELS = {
    "Heltec_V3_placeholder": heltec_boxes,
    "Mini360_placeholder": mini360_boxes,
}


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, fn in MODELS.items():
        boxes = fn()
        write_wrl(os.path.join(OUT_DIR, name + ".wrl"), boxes)
        write_step(os.path.join(OUT_DIR, name + ".step"), name, boxes)
        print(f"wrote gate_node.3dshapes/{name}.wrl/.step ({len(boxes)} boxes)")


if __name__ == "__main__":
    main()
